"""Pin WHERE each MSPDI fixture came from, so no session mistakes one class for the other.

This guard exists because a session nearly validated a CPM change against a fixture that could not
adjudicate it (ADR-0391). The synthetic battery in ``tests/fixtures/test_projects/`` is written by
``tools/make_test_projects.py``, whose scheduler pins a started task at its actual dates. Using its
stored ``<Finish>`` to confirm an engine rule that implements the *same* assumption is circular —
the fixture agrees because both sides share a model, not because MS Project said so.

The genuine exports in ``tests/fixtures/golden/`` are different in kind: MS Project wrote them, so
they carry its OWN computed schedule (``EarlyStart``/``EarlyFinish``/``LateStart``/``LateFinish``/
``Critical``) and its progress bookkeeping (``Stop``/``Resume``). Those fields are a real oracle;
the battery has none of them.

So the two classes are pinned in BOTH directions. If someone teaches the generator to emit
``EarlyFinish``, or a golden loses it, this fails and forces the question to be asked out loud
rather than assumed. It deliberately asserts the *presence and absence of fields*, never a date —
the dates belong to the parity/Fuse tests.

Note the corollary ADR-0391 turned on: the battery carries no ``Stop``/``Resume``, so ADR-0309's
progress-override floor can never fire on it, and no amount of regenerating changes that (MS
Project writes ``resume == stop`` for contiguous progress). A fix keyed on ``ActualStart``, which
the battery DOES carry, is unaffected.
"""

from __future__ import annotations

import xml.etree.ElementTree as ET
from pathlib import Path

import pytest

_NS = "{http://schemas.microsoft.com/project}"

FIXTURES = Path(__file__).resolve().parents[1] / "fixtures"

#: MS Project writes these on every task of a real export; the generator writes none of them.
_MSP_COMPUTED = ("EarlyStart", "EarlyFinish", "LateStart", "LateFinish", "Critical")

#: Written by MS Project on progressed tasks only — the ADR-0309 input the battery cannot express.
_MSP_PROGRESS = ("Stop", "Resume")

#: Genuine MS Project exports: (path, expected task count).
_REAL_EXPORTS = [
    ("golden/project2_5/Project2.mspdi.xml", 145),
    ("golden/project2_5/Project5.mspdi.xml", 145),
    ("golden/evm/EVM1.mspdi.xml", 15),
    ("golden/evm/EVM2.mspdi.xml", 15),
]

#: Generated by tools/make_test_projects.py — constructed truth, not an MS Project oracle.
_GENERATED = [
    "test_projects/TP1_Library_Progressed.xml",
    "test_projects/TP2_Bridge_4x10_Calendar.xml",
    "test_projects/TP3_Outage_DCMA_Seeded.xml",
    "test_projects/TP4_DataCenter_v1.xml",
    "test_projects/TP4_DataCenter_v2.xml",
    "test_projects/TP4_DataCenter_v3.xml",
    "test_projects/TP4_DataCenter_v4.xml",
    "test_projects/TP4_DataCenter_v5.xml",
]


def _tasks(rel: str) -> list[ET.Element]:
    root = ET.parse(FIXTURES / rel).getroot()
    return [t for t in root.iter(f"{_NS}Task") if t.findtext(f"{_NS}UID") is not None]


def _count_with(tasks: list[ET.Element], tag: str) -> int:
    return sum(1 for t in tasks if t.find(f"{_NS}{tag}") is not None)


@pytest.mark.parametrize(("rel", "expected_tasks"), _REAL_EXPORTS)
def test_real_exports_carry_ms_projects_computed_schedule(rel: str, expected_tasks: int) -> None:
    """A golden is an oracle because MS Project's own dates are IN it — on every task."""
    tasks = _tasks(rel)
    assert len(tasks) == expected_tasks, (rel, len(tasks))
    for tag in _MSP_COMPUTED:
        assert _count_with(tasks, tag) == expected_tasks, (rel, tag)


@pytest.mark.parametrize(("rel", "_expected"), _REAL_EXPORTS)
def test_real_exports_carry_progress_bookkeeping(rel: str, _expected: int) -> None:
    """Stop/Resume ride on the progressed tasks of a real export (the ADR-0309 input)."""
    tasks = _tasks(rel)
    for tag in _MSP_PROGRESS:
        assert _count_with(tasks, tag) > 0, (rel, tag)


@pytest.mark.parametrize("rel", _GENERATED)
def test_generated_battery_is_not_an_ms_project_export(rel: str) -> None:
    """The battery carries NONE of MS Project's computed fields and no Stop/Resume.

    Its stored dates are constructed truth from ``tools/make_test_projects.py`` — useful, and
    corroborated for TP4 by the operator's Acumen Fuse run (``docs/FUSE-VALIDATION.md``), but not
    self-evidencing. Do not treat a value read out of these files as "what MS Project computed".
    """
    tasks = _tasks(rel)
    assert tasks, rel
    for tag in (*_MSP_COMPUTED, *_MSP_PROGRESS):
        assert _count_with(tasks, tag) == 0, (rel, tag, "battery gained an MS Project field")


@pytest.mark.parametrize("rel", _GENERATED)
def test_generated_battery_still_carries_the_actual_starts_adr_0391_reads(rel: str) -> None:
    """The positive control for the negative test above.

    Asserting only absences would pass just as well against an empty or unparsed file, so pin the
    field ADR-0391's floor actually consumes: every battery file that records progress carries
    ``ActualStart``. TP2 is the deliberate exception — a 0%-complete, unstarted schedule.
    """
    tasks = _tasks(rel)
    started = _count_with(tasks, "ActualStart")
    if rel.endswith("TP2_Bridge_4x10_Calendar.xml"):
        assert started == 0, (rel, "TP2 is the unstarted case")
    else:
        assert started > 0, (rel, "battery file lost the ActualStart ADR-0391 reads")
