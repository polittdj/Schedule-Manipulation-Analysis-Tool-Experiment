"""Deterministic synthetic-MSPDI generator for row-count scale tests (WP1 / S5).

``TP5_LongSpan_Synthetic.xml`` carries the SPAN payload at 121 tasks (ADR-0441: the long-span
rendering defects reproduce at any row count). The S5 defect is the opposite axis — ROW COUNT
(the operator's 2,301-activity IPMR; one-shot ``paintRows`` measured 1,417 ms at 2,280 rows) —
and a committed multi-thousand-task XML would be a large binary-ish blob for no reason. So the
row-scale look-alike is GENERATED, deterministically, at test time: same recipe as TP5 (FS
chains, ~15% milestones, 8h Standard calendar, status date inside the span), parameterized by
task count. Fictional throughout — synthetic, non-CUI by construction (Law 1).

Determinism matters for QC-1: two runs of a probe must disagree only because the code changed,
never because the fixture did. ``random.Random(seed)`` with a fixed default guarantees it.
"""

