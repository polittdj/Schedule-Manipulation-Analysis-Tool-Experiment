_STATUS = datetime(2026, 1, 16)


def _next_workday(d: datetime) -> datetime:
    while d.weekday() >= 5:
        d += timedelta(days=1)
    return d


def generate_mspdi(tasks: int, chains: int = 24, seed: int = 42, span_days: int = 4500) -> str:
    """Return MSPDI XML text with exactly ``tasks`` leaf tasks in ``chains`` FS chains."""
    rng = random.Random(seed)
    start0 = datetime(2017, 6, 5)
    parts: list[str] = [_HEADER]
    finish_all = start0 + timedelta(days=span_days)
    parts.append(
        "    <Task>\n"
        "      <UID>0</UID><ID>0</ID><Name>SYNTH - Row-scale Look-alike</Name>\n"
        "      <Active>1</Active><Manual>0</Manual><Type>0</Type><IsNull>0</IsNull>\n"
        "      <OutlineLevel>0</OutlineLevel><Priority>500</Priority>\n"
        f"      <Start>{start0:%Y-%m-%d}T08:00:00</Start>\n"
        f"      <Finish>{finish_all:%Y-%m-%d}T17:00:00</Finish>\n"
        f"      <Duration>PT{span_days * 8}H0M0S</Duration><DurationFormat>7</DurationFormat>\n"
        "      <Milestone>0</Milestone><Summary>1</Summary>\n"
        "      <ConstraintType>0</ConstraintType>\n"
        "    </Task>\n"
    )
    per_chain = [tasks // chains + (1 if i < tasks % chains else 0) for i in range(chains)]
    # each chain packs its steps across the span so the LAST step lands near span end
    uid = 0
    for ci, n in enumerate(per_chain):
        if n <= 0:
            continue
        cursor = _next_workday(start0 + timedelta(days=rng.randint(0, 25)))
        # average calendar days per step so the chain roughly spans the project
        pace = max(1, (span_days - 60) // max(1, n))
        prev_uid = None
        for si in range(n):
            uid += 1
            is_ms = rng.random() < 0.15
            if is_ms:
                s = f = _next_workday(cursor)
                dur_h = 0
            else:
                cal_days = max(1, min(pace + rng.randint(-2, 2), 260))
                s = _next_workday(cursor)
                f = s + timedelta(days=cal_days)
                # working-day-ish duration for the importer; 5/7 of the calendar days, 8h each
                dur_h = max(8, int(cal_days * 5 / 7) * 8)
                cursor = f + timedelta(days=1)
            if f <= _STATUS:
                pct = 100
            elif s >= _STATUS:
                pct = 0
            else:
                pct = 40
            name = f"Chain {ci + 1:02d} step {si + 1:03d}"
            rows = [
                "    <Task>",
                f"      <UID>{uid}</UID><ID>{uid}</ID><Name>{name}</Name>",
                "      <Active>1</Active><Manual>0</Manual><Type>0</Type><IsNull>0</IsNull>",
                "      <OutlineLevel>1</OutlineLevel><Priority>500</Priority>",
                f"      <Start>{s:%Y-%m-%d}T08:00:00</Start><Finish>{f:%Y-%m-%d}T17:00:00</Finish>",
                f"      <Duration>PT{dur_h}H0M0S</Duration><DurationFormat>7</DurationFormat>",
                f"      <Milestone>{1 if is_ms else 0}</Milestone><Summary>0</Summary>",
                f"      <PercentComplete>{pct}</PercentComplete>",
            ]
            if pct == 100:
                rows.append(
                    f"      <ActualStart>{s:%Y-%m-%d}T08:00:00</ActualStart>"
                    f"<ActualFinish>{f:%Y-%m-%d}T17:00:00</ActualFinish>"
                )
            rows.append("      <ConstraintType>0</ConstraintType>")
            if prev_uid is not None:
                rows.append(
                    f"      <PredecessorLink><PredecessorUID>{prev_uid}</PredecessorUID>"
                    "<Type>1</Type><CrossProject>0</CrossProject><LinkLag>0</LinkLag>"
                    "<LagFormat>7</LagFormat></PredecessorLink>"
                )
            rows.append("    </Task>")
            parts.append("\n".join(rows) + "\n")
            prev_uid = uid
    parts.append("  </Tasks>\n</Project>\n")
    return "".join(parts)
