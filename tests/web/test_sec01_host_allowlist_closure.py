"""SEC-01 completion — behavioural closure over ``_ALLOWED_HOSTS`` (the ADR-0394 recipe).

The audit pinned the allowlist's DATA
(``tests/audit/test_audit_findings.py::test_sec01_allowed_hosts_pinned_to_exact_loopback_set``)
and ``test_sec_hardening.py`` samples both consumers' behaviour. Measured 2026-08-14 in
mutant sandboxes (import-origin proven per run), that pairing still left three holes, each
the exact class ADR-0394 closed for ``net_guard``:

* **M1 blindness of the samples**: with ``"evil.example"`` ADDED to the frozenset, all 9
  ``test_sec_hardening`` tests stayed green (its samples use other literals) — only the
  data pin fired. A sampled negative can never see a *named* entry added beside it.
* **M3 caught by NOTHING**: dropping the ``scheme in ("http", "https")`` conjunct from
  ``_origin_allowed`` left the data pin, the hardening suite, tests/audit AND tests/guards
  all green. An ``ftp://`` / ``file://`` Origin then passes the CSRF fallback.
* **M5 needs the HTTP layer**: gating the middleware call site off (``if False:``) leaves
  every unit truth about ``_host_allowed`` intact — only requests through the app see it.

This module is the closure sweep: hand-curated populations (every member's verdict is
justified by construction, none derived from the code under test), swept THROUGH the HTTP
layer, asserted in BOTH directions plus one whole-population closure per consumer, so a
widening, a bypass, an unwiring and a feature-breaking narrowing all fail by name.
Mutation battery (M1-M5): see the ADR for this change; every flip was verified against
this committed module in a sandbox with the import origin printed and asserted.

No real gateway name appears here (DISC-01); the attack hosts are inert test literals
(``evil.example``, ``evil.com``, …) that nothing ever resolves — TestClient is in-process
ASGI, no socket is opened.

The ADR-0240 adversarial round on the first revision found and this revision closes: a
method-conditional host-check bypass no test in the repo could see (the sweep was GET-only
and the existing POST case was laundered by ``follow_redirects=True`` — the POST row below
plus the ``follow_redirects=False`` fix in ``test_sec_hardening.py``); the empty-Origin
row (an ``if not origin_header`` fail-open escaped everything); and two dead-oracle
constants now load-bearing as in-module data pins (``EXPECTED_ALLOWED_HOSTS``,
``EXPECTED_UNSAFE_METHODS`` — the latter pinned as data because the app registers no
mutating non-POST route to probe behaviourally).
"""

from __future__ import annotations

import asyncio
from typing import Any

import pytest
from fastapi.testclient import TestClient

from schedule_forensics.web.app import SessionState, create_app

#: Test-side literal (NEVER imported from app.py — an oracle that reads the value it
#: judges refutes nothing). Asserted against the live frozenset below, in lockstep with
#: the tests/audit data pin.
EXPECTED_ALLOWED_HOSTS = frozenset({"127.0.0.1", "localhost", "::1", "testserver"})

#: The methods SEC-2 gates. Pinned as DATA: the app registers no PUT/PATCH/DELETE route
#: today, so a narrowing is unprobeable behaviourally yet would silently un-gate any
#: future mutating route (adversarial round: narrowing to {"POST"} escaped every test).
EXPECTED_UNSAFE_METHODS = frozenset({"POST", "PUT", "PATCH", "DELETE"})

# --------------------------------------------------------------------------------------
# Populations. Verdicts are by construction: a served form is a genuine loopback/test
# name as HTTP actually spells it; everything refused is either not this machine or a
# malformed/fail-closed spelling. Neither list is generated by the code under test.
# --------------------------------------------------------------------------------------

#: Host-header confusables built from the allowlist names — the shapes a prefix/suffix/
#: substring/subdomain matcher would accept.
_HOST_CONFUSABLES: tuple[str, ...] = tuple(
    template.format(name=name)
    for name in ("localhost", "127.0.0.1")
    for template in (
        "{name}.evil.com",  # subdomain-of-remote: the classic rebinding Host
        "not{name}",
        "{name}x",
        "{name}-proxy",
        "{name}.local",
        "www.{name}",
    )
)

#: Host headers that must be REFUSED (400, before any route runs).
_REFUSED_HOSTS: tuple[str, ...] = (
    "evil.example",
    "evil.example:8000",  # port must not launder a foreign name
    "127.0.0.2",  # exact-string set: unlike net_guard there is no 127/8 acceptance
    "10.0.0.5:8471",  # another machine on the LAN
    "0.0.0.0",  # "every interface" is not "this machine only"
    "2130706433",  # 127.0.0.1 packed decimal — not a valid IP literal
    # IDN homograph of localhost (Cyrillic o) as a browser actually TRANSPORTS it: the
    # punycode form. Raw non-ASCII cannot ride an HTTP/1.1 Host header at all (httpx
    # refuses to encode it — measured), so the ASCII IDNA spelling is the real vector.
    "xn--lcalhost-nbh",
    "localhost.",  # trailing-dot FQDN — fail-closed
    # HTTP spells IPv6 hosts in brackets; the raw form is not a valid Host header and
    # rejecting it is the fail-closed direction (the frozenset's "::1" is reachable
    # ONLY via "[::1]"). Pinned so a "helpful" unbracketed acceptance shows up here.
    "::1",
    # NOTE the unmatched-bracket form "[::1" is deliberately NOT in this population: at the
    # declared dependency FLOOR (starlette 0.37.2 — measured on CI and reproduced in a
    # floor venv) the app's own liveness middleware raises server-side on it
    # (request.url.path parses the Host header; `finally` runs even on refused requests),
    # so the row is untransportable through the HTTP layer across the supported range.
    # Its ValueError branch is pinned unit-level below instead.
    "",  # empty Host
    *_HOST_CONFUSABLES,
)

#: Host headers that must be SERVED (200) — the true-positive twin: the pin must not be
#: satisfiable by refusing everything (Law 2: never weaken the feature to pass a test).
_SERVED_HOSTS: tuple[str, ...] = (
    "127.0.0.1",
    "127.0.0.1:8000",
    "127.0.0.1:8471",
    "localhost",
    "localhost:8471",
    "LOCALHOST",  # urlsplit().hostname lowercases
    "localhost:notaport",  # .hostname never validates the port part
    "[::1]",
    "[::1]:8000",
    "testserver",  # Starlette TestClient's default — single-label, publicly unresolvable
    " 127.0.0.1 ",  # the middleware strips
)

#: Origins that must be REFUSED (403) on the CSRF fallback path (unsafe method, NO
#: Sec-Fetch-Site header — setting SFS would bypass the fallback under test entirely).
_REFUSED_ORIGINS: tuple[str, ...] = (
    "https://evil.example",
    "http://evil.example:8471",
    "http://127.0.0.2",
    "http://localhost.evil.com",
    "null",  # a sandboxed/serialized origin is not provably same-site
    "ftp://127.0.0.1",  # scheme matters, not just the host (the M3 hole)
    "file://localhost/etc/passwd",
    "127.0.0.1",  # scheme-less
    # Empty-string Origin: refused today, and pinned so an `if not origin_header`
    # fail-open (absent and empty conflated) goes red (adversarial round).
    "",
)

#: Origins that must PASS the fallback (200) — loopback origins as browsers send them.
#: ``http://testserver`` documents that the shared frozenset admits the test host here
#: too: deliberate, harmless (publicly unresolvable), and pinned so it cannot drift
#: silently into something wider.
_ALLOWED_ORIGINS: tuple[str | None, ...] = (
    None,  # absent Origin = non-browser local client (curl, tests) — not the CSRF vector
    "http://127.0.0.1",
    "http://127.0.0.1:8471",
    "https://localhost",
    "http://[::1]:8471",
    "http://testserver",
)

#: Schemes swept on a loopback Origin: accepted set must close over exactly http/https.
_SWEPT_ORIGIN_SCHEMES: tuple[str, ...] = (
    "http",
    "https",
    "ftp",
    "ftps",
    "file",
    "ws",
    "wss",
    "data",
    "gopher",
    "javascript",
    "chrome-extension",
)


@pytest.fixture
def client() -> TestClient:
    return TestClient(create_app(SessionState()))


# --------------------------------------------------------------------------------------
# Consumer 1: the Host allowlist middleware (SEC-3, DNS rebinding).
# --------------------------------------------------------------------------------------


@pytest.mark.parametrize("host", _REFUSED_HOSTS)
def test_every_foreign_host_form_is_refused_before_any_route_runs(
    client: TestClient, host: str
) -> None:
    r = client.get("/api/whoami", headers={"host": host})
    assert r.status_code == 400, host
    assert r.json() == {"error": "invalid host header"}
    # the refusal itself still carries the air-gap headers (Law 1 on every response)
    assert "Content-Security-Policy" in r.headers


@pytest.mark.parametrize("host", _SERVED_HOSTS)
def test_every_loopback_host_form_is_still_served(client: TestClient, host: str) -> None:
    assert client.get("/api/whoami", headers={"host": host}).status_code == 200, host


def test_served_hosts_are_exactly_the_expected_ones(client: TestClient) -> None:
    """Closure over the whole population, both directions named in one diff."""
    population = _REFUSED_HOSTS + _SERVED_HOSTS
    served = {
        host
        for host in population
        if client.get("/api/whoami", headers={"host": host}).status_code == 200
    }
    assert served == set(_SERVED_HOSTS), (
        f"unexpectedly served: {sorted(served - set(_SERVED_HOSTS))!r}; "
        f"unexpectedly refused: {sorted(set(_SERVED_HOSTS) - served)!r}"
    )


def test_the_host_check_gates_unsafe_methods_too(client: TestClient) -> None:
    """A host-check bypass conditioned on the METHOD (e.g. checking only GETs) was,
    measured, caught by nothing in the repo: this module swept hosts via GET only, and
    the existing hardening POST case was laundered by ``follow_redirects=True`` (the
    followed redirect GET got the 400 while the POST had already run). /api/heartbeat
    returns directly — no redirect to launder — so this row dies on the mutant."""
    r = client.post("/api/heartbeat", headers={"host": "evil.example"})
    assert r.status_code == 400
    assert r.json() == {"error": "invalid host header"}


def test_an_unparseable_host_header_is_refused_by_the_check_itself() -> None:
    """The urlsplit ValueError branch of ``_host_allowed`` (unmatched IPv6 bracket),
    pinned at the UNIT level: the HTTP-layer variant of this row is version-dependent —
    at the declared floor, starlette's ``request.url`` raises on the malformed Host
    inside the app before any status exists (see the population note above), so the
    branch is exercised on the function the middleware calls, not through a transport
    that cannot carry the input everywhere the tree must pass."""
    from schedule_forensics.web.app import _host_allowed

    assert _host_allowed("[::1") is False


def test_the_allowlist_literal_is_exactly_the_expected_set() -> None:
    """In-module data pin (the ADR-0394 recipe's first layer, self-contained here):
    the module-top literal must actually be asserted, not just declared."""
    from schedule_forensics.web.app import _ALLOWED_HOSTS

    assert _ALLOWED_HOSTS == EXPECTED_ALLOWED_HOSTS


def test_the_unsafe_method_set_is_exactly_the_mutating_verbs() -> None:
    """Data pin for SEC-2's method gate — see EXPECTED_UNSAFE_METHODS' comment for why
    this cannot be a behavioural probe today."""
    from schedule_forensics.web.app import _UNSAFE_METHODS

    assert _UNSAFE_METHODS == EXPECTED_UNSAFE_METHODS


def test_a_request_with_no_host_header_at_all_is_refused() -> None:
    """HTTP/1.0-style absent Host. httpx cannot send a truly missing Host header, so the
    request is driven through the raw ASGI interface; the middleware must default the
    absent header to "" and refuse it (fail-closed, HTTP/1.1 requires a Host)."""
    app = create_app(SessionState())
    scope: dict[str, Any] = {
        "type": "http",
        "asgi": {"version": "3.0"},
        "http_version": "1.0",
        "method": "GET",
        "path": "/api/whoami",
        "raw_path": b"/api/whoami",
        "root_path": "",
        "query_string": b"",
        "headers": [],
        "client": ("127.0.0.1", 12345),
        "server": ("127.0.0.1", 8321),
        "scheme": "http",
    }
    statuses: list[int] = []

    async def receive() -> dict[str, Any]:
        return {"type": "http.request", "body": b"", "more_body": False}

    async def send(message: dict[str, Any]) -> None:
        if message["type"] == "http.response.start":
            statuses.append(message["status"])

    asyncio.run(app(scope, receive, send))
    assert statuses == [400]


# --------------------------------------------------------------------------------------
# Consumer 2: the CSRF Origin fallback (SEC-2, unsafe methods, Sec-Fetch-Site absent).
# NOTE: a foreign Origin under ``Sec-Fetch-Site: same-origin`` passes BY DESIGN
# (ADR-0268 — SFS is the primary, browser-forged-proof signal); that interplay is
# asserted in test_sec_hardening.py and deliberately not re-gated here.
# --------------------------------------------------------------------------------------


@pytest.mark.parametrize("origin", _REFUSED_ORIGINS)
def test_csrf_fallback_refuses_every_foreign_origin(client: TestClient, origin: str) -> None:
    r = client.post("/api/heartbeat", headers={"origin": origin})
    assert r.status_code == 403, origin
    assert r.json() == {"error": "cross-site request refused"}


@pytest.mark.parametrize("origin", _ALLOWED_ORIGINS)
def test_csrf_fallback_still_passes_loopback_and_absent_origins(
    client: TestClient, origin: str | None
) -> None:
    headers = {} if origin is None else {"origin": origin}
    assert client.post("/api/heartbeat", headers=headers).status_code == 200, origin


def test_csrf_fallback_origin_schemes_close_over_exactly_http_and_https(
    client: TestClient,
) -> None:
    """The M3 hole: the scheme conjunct in ``_origin_allowed`` was, measured, guarded by
    no test anywhere. A loopback host is necessary but not sufficient."""
    accepted = {
        scheme
        for scheme in _SWEPT_ORIGIN_SCHEMES
        if client.post("/api/heartbeat", headers={"origin": f"{scheme}://127.0.0.1"}).status_code
        == 200
    }
    assert accepted == {"http", "https"}, (
        f"unexpectedly accepted Origin schemes: {sorted(accepted - {'http', 'https'})!r}; "
        f"unexpectedly refused: {sorted({'http', 'https'} - accepted)!r}"
    )


def test_csrf_fallback_accepts_exactly_the_expected_origins(client: TestClient) -> None:
    """Closure over the whole Origin population, both directions named in one diff."""
    population: tuple[str | None, ...] = _REFUSED_ORIGINS + _ALLOWED_ORIGINS
    accepted = {
        origin
        for origin in population
        if client.post(
            "/api/heartbeat", headers={} if origin is None else {"origin": origin}
        ).status_code
        == 200
    }
    assert accepted == set(_ALLOWED_ORIGINS), (
        f"unexpectedly accepted: {sorted(str(o) for o in accepted - set(_ALLOWED_ORIGINS))!r}; "
        f"unexpectedly refused: {sorted(str(o) for o in set(_ALLOWED_ORIGINS) - accepted)!r}"
    )
