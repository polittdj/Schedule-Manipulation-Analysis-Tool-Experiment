def test_orbit_motion_is_css_only_transform_only_token_colors(client: TestClient) -> None:
    """The plan's motion decision, executable: the dots animate via CSS transform ONLY (no
    layout-property animation), are colored by theme tokens only, and NO JS touches them."""
    css = client.get("/static/base.css").text
    assert ".load-orbit{" in css and ".orbit-dot{" in css
    # the keyframes body animates transform and nothing else
    kf = css.split("@keyframes sf-orbit{", 1)[1].split("}}", 1)[0]
    assert "transform:" in kf
    for prop in ("left:", "top:", "width:", "height:", "margin"):
        assert prop not in kf, f"sf-orbit animates {prop} — transform-only is the rule"
    # token colors only in the orbit block (from .orbit-dot to the keyframes)
    block = css.split(".orbit-dot{", 1)[1].split("@keyframes sf-orbit", 1)[0]
    assert "var(--accent)" in css.split(".orbit-dot{", 1)[1][:200]
    assert "var(--ok)" in block and "var(--warn)" in block
    assert not re.search(r"#[0-9a-fA-F]{3,8}\b", block), "orbit colors must be theme tokens"
    # zero JS: neither the hum module nor home.js knows the orbit exists
    assert "orbit" not in client.get("/static/launch_audio.js").text
    assert "orbit" not in client.get("/static/home.js").text


