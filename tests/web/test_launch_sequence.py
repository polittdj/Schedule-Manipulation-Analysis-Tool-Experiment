def test_the_hum_is_synthesized_gesture_primed_and_assetless(client: TestClient) -> None:
    """The Boot Audio Hum is generated by WebAudio — no audio asset exists anywhere, nothing is
    fetched, and the context is created only inside prime() (the gesture-only act)."""
    resp = client.get("/static/launch_audio.js")
    assert resp.status_code == 200
    js = resp.text
    assert "AudioContext" in js and "createOscillator" in js  # synthesis, not playback
    for banned in (".ogg", ".mp3", ".wav", "new Audio", "fetch(", "XMLHttpRequest", "<audio"):
        assert banned not in js, f"the hum must be synthesized — found {banned!r}"
    # no audio asset ships in the static tree (the wheel/installers stay lean)
    for ext in (".ogg", ".mp3", ".wav", ".m4a", ".opus", ".flac"):
        assert not list(STATIC.glob(f"**/*{ext}")), f"an audio asset landed in static/ ({ext})"
    # persisted controls under the house localStorage pattern (cf. theme.js sf-theme/sf-scale)
    assert "sf-hum-mute" in js and "sf-hum-vol" in js and "localStorage" in js
    # every level change is a ramp (a stepped gain clicks) and the fade is capped at 200ms
    assert js.count("linearRampToValueAtTime") >= 5
    assert "FADE_CAP_MS = 200" in js and "Math.min(ms, FADE_CAP_MS)" in js


def test_the_hum_is_a_shuffled_pattern_not_a_loop(client: TestClient) -> None:
    """OR-03's sound-quality clause, executable at the text level: swell pitches come from a
    SHUFFLED BAG over a real pitch set (a series of similar sounds — all sound before any
    repeats, refills never repeat back-to-back), the scheduler is a lookahead loop on the audio
    clock with jittered spacing (no loop point, hence no seam to mix), and it runs until stopped
    (a minute-long load hums for the whole minute — no fixed clip length)."""
    js = client.get("/static/launch_audio.js").text
    pitches = js.split("PITCHES = [", 1)[1].split("]", 1)[0]
    assert len(pitches.split(",")) >= 6, "the swell set is a real series, not one tone"
    assert "shuffledBag" in js and "Math.random" in js
    assert "lastPitch" in js  # the no-back-to-back-repeat guard across refills
    assert "ctx.currentTime + 0.8" in js  # lookahead scheduling on the AUDIO clock
    assert "1.5 + Math.random() * 0.9" in js  # jittered spacing: a pattern, not a metronome
    assert "setInterval" in js  # topped up for as long as the load runs — no fixed duration


def test_home_primes_only_in_gesture_handlers_and_fades_before_navigating(
    client: TestClient,
) -> None:
    """The autoplay decision, executable: prime() is called from exactly the four genuine
    gesture handlers — pick, folder, example submit, drop — and NEVER from input.onchange;
    the upload path fades the hum BEFORE ``window.location`` navigates; every error path
    stops the hum with the overlay."""
    js = client.get("/static/home.js").text
    assert js.count("hum('prime')") == 4  # pick / folder / example-submit / drop
    # neither onchange handler primes (change may not carry user activation)
    for stmt in re.findall(r"onchange = function[^}]*}", js):
        assert "prime" not in stmt, "input.onchange must never prime the audio context"
    # the fade precedes the navigation, so the redirect cuts silence, not sound
    assert "hum('fade')" in js and "window.location" in js
    assert js.index("hum('fade')") < js.index("window.location = (data && data.redirect)")
    assert js.count("hum('stop')") >= 3  # preread failure, nothing readable, upload failure
    assert "hum('start')" in js  # the hum starts when the overlay shows


