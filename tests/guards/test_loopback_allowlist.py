"""The loopback allowlist is DATA — and unpinned data is not a guarantee (Law 1, CUI).

Every locality decision the tool makes funnels through two frozensets in
``net_guard``: ``_LOOPBACK_HOSTNAMES`` (which *names* mean "this machine") and
``_LOCAL_HTTP_SCHEMES`` (which URL schemes may carry a model request). Between
them they gate ``is_loopback_host`` / ``is_local_http_endpoint``, and through
those every enforcement point in the product — ``ai/ollama.py``,
``ai/openai_compat.py``, the settings endpoint validators in ``web/app.py``, and
``launcher.py``'s bind check.

**Nothing pinned their contents.** ``docs/PLAN/APPROVED-GATEWAY-INTEGRATION.md``
§2 reported this; it was re-measured here rather than taken on trust. With
``proxy.fast.luna.nasa.gov`` added to ``_LOOPBACK_HOSTNAMES`` in a sandbox — so
that ``is_loopback_host("proxy.fast.luna.nasa.gov")`` returned ``True`` — the
guard, AI, air-gap, startup, launcher and exhibit-CLI suites ran **336 passed, 0
failed**, this module deselected. The negative cases those suites pin
(``tests/guards/test_egress.py``, ``tests/guards/test_endpoint_scheme.py``) are
*sampled literals* — ``8.8.8.8``, ``example.com``, ``evil.com`` — and a sampled
negative can never see a *named* allowlist entry added beside it. So the single
most consequential edit available in this repo was invisible to CI, to review,
and to a future audit reading a green suite.

This module closes that gap two ways, because either alone is escapable:

* **Data pins** assert the frozensets are *exactly* their expected literals. These
  catch a widening (a gateway hostname added) and a narrowing (an entry dropped)
  by name, and they fail loudly enough that the diff cannot be mistaken for
  routine churn.
* **Behavioural closure sweeps** assert which hosts/schemes are actually accepted,
  over a hand-curated population every member of which is unambiguously not this
  machine. These survive a refactor of the data structure and — unlike the data
  pins — still fire when the allowlist is bypassed rather than widened, e.g. a
  ``candidate.endswith(".nasa.gov")`` short-circuit added *above* the frozenset
  check, which leaves the literal provably untouched.

The expected values are written here as test-side literals and are deliberately
**not** imported from the module under test: an oracle that reads the value it is
judging cannot refute anything (QC-1). Likewise the populations below are fixed
and hand-audited rather than derived from ``is_loopback_host``, so the expected
verdict for every non-loopback member is the constant ``False``, justified by
construction rather than by asking the implementation what it thinks.

Mutation-proved: see ``docs/adr/0394-pin-the-loopback-allowlist.md`` for the
battery and its results.
"""

from __future__ import annotations

from ipaddress import ip_address
from urllib.parse import urlparse

import pytest

from schedule_forensics import net_guard

# --------------------------------------------------------------------------------------
# Expected values — test-side literals, NEVER imported from net_guard (QC-1: an oracle
# must be independent of the thing it judges).
# --------------------------------------------------------------------------------------

#: The only host *names* that may mean "this machine". Anything else must resolve
#: through the ``ipaddress`` loopback branch or be refused.
EXPECTED_LOOPBACK_HOSTNAMES = frozenset({"localhost", "ip6-localhost"})

#: The only URL schemes a model endpoint may use. A loopback host is necessary but
#: not sufficient (``file://localhost/etc/passwd`` carries a loopback host).
EXPECTED_LOCAL_HTTP_SCHEMES = frozenset({"http", "https"})

#: The approved gateway from ``docs/PLAN/APPROVED-GATEWAY-INTEGRATION.md`` §1. It is
#: named here on purpose: this is the exact hostname added to the allowlist on the
#: operator's machine, and the exact edit that CI could not see.
APPROVED_GATEWAY_HOST = "proxy.fast.luna.nasa.gov"


# --------------------------------------------------------------------------------------
# Populations. Every member of _NON_LOOPBACK is, by construction, not this machine;
# every member of _LOOPBACK is. Neither list is generated by the code under test.
# --------------------------------------------------------------------------------------

#: Confusables built from the allowlist literals — the shapes an attacker or a
#: well-meaning patch reaches for. A guard that matches by prefix, suffix, substring
#: or subdomain instead of by equality accepts at least one of these.
_CONFUSABLES: tuple[str, ...] = tuple(
    template.format(name=name)
    for name in sorted(EXPECTED_LOOPBACK_HOSTNAMES)
    for template in (
        "{name}.example.com",  # subdomain-of-remote: the classic allowlist bypass
        "{name}.nasa.gov",
        "not{name}",
        "{name}x",
        "x{name}",
        "{name}-proxy",
        "{name}.local",  # mDNS, a different machine on the LAN
        "{name}.",  # trailing-dot FQDN — rejecting is the fail-closed direction
        "www.{name}",
        "{name}:11434",  # a netloc passed where a hostname was expected
    )
)

#: Hosts that must never be treated as local. Curated, not derived.
_NON_LOOPBACK: tuple[str, ...] = (
    # -- the approved gateway and every parent of it (a suffix rule accepts these) ------
    APPROVED_GATEWAY_HOST,
    "fast.luna.nasa.gov",
    "luna.nasa.gov",
    "nasa.gov",
    # -- ordinary remote hosts ---------------------------------------------------------
    "example.com",
    "evil.com",
    "api.openai.com",
    "8.8.8.8",
    "1.1.1.1",
    # -- other machines that are reachable but are NOT this one ------------------------
    "10.0.0.5",
    "192.168.1.10",
    "172.16.0.1",
    "169.254.1.1",  # link-local
    "fe80::1",  # IPv6 link-local
    "2001:4860:4860::8888",  # public IPv6
    # -- wildcard binds: "every interface" is not "this machine only" ------------------
    "0.0.0.0",  # asserted REJECTED, never bound
    "::",
    # -- loopback-looking but remote ---------------------------------------------------
    "127.0.0.1.evil.com",
    "localhost.evil.com",
    # -- a decimal-integer IP form; `ipaddress` refuses it, so the guard must too -------
    "2130706433",  # = 127.0.0.1 packed, but not a valid IP literal
    # -- IDN homograph: Cyrillic U+043E in place of ASCII 'o'. Written as an escape so
    #    the confusable cannot be "helpfully" normalized away by an editor or a linter.
    "l\u043ecalhost",
    # -- degenerate input --------------------------------------------------------------
    "",
    "   ",
    "not-a-host",
    *_CONFUSABLES,
)

#: Hosts that legitimately mean this machine — the allowlist names in their accepted
#: case/whitespace forms, plus the loopback IP literals `ipaddress` resolves.
_LOOPBACK: tuple[str, ...] = (
    "localhost",
    "LOCALHOST",
    "ip6-localhost",
    "IP6-Localhost",
    "127.0.0.1",
    "127.0.0.5",  # the whole 127/8 block is loopback
    "::1",
    "[::1]",  # bracketed IPv6, as it appears in a URL netloc
    " 127.0.0.1 ",
)

#: Schemes swept against a loopback host to pin which ones may carry a request.
_SWEPT_SCHEMES: tuple[str, ...] = (
    "http",
    "https",
    "ftp",
    "ftps",
    "sftp",
    "file",
    "gopher",
    "data",
    "ws",
    "wss",
    "ssh",
    "telnet",
    "ldap",
    "jar",
    "netdoc",
    "blob",
    "javascript",
)


# --------------------------------------------------------------------------------------
# 1. Data pins — exact contents, by name.
# --------------------------------------------------------------------------------------


def test_loopback_hostname_allowlist_is_exactly_the_expected_names() -> None:
    """The allowlist is a security constant; its contents are pinned like one.

    Adding a hostname here re-labels a remote machine as "local" everywhere in the
    codebase at once — including in every on-screen sovereignty claim. Changing this
    set is an ADR-level decision, so make the test say so out loud.
    """
    assert net_guard._LOOPBACK_HOSTNAMES == EXPECTED_LOOPBACK_HOSTNAMES, (
        "net_guard._LOOPBACK_HOSTNAMES changed. This frozenset is the whole Law-1 "
        "locality guarantee: every name in it is treated as THIS MACHINE by "
        "is_loopback_host, and so by every AI backend, endpoint validator and bind "
        "check in the product. Widening it to reach a remote model server is the "
        "single most dangerous edit available in this repo, and it must never be "
        "made to make a gateway work — build a named, non-local backend instead "
        "(docs/PLAN/APPROVED-GATEWAY-INTEGRATION.md §6). If this change is genuinely "
        "intended, write the ADR first, then update EXPECTED_LOOPBACK_HOSTNAMES here."
    )


def test_local_http_scheme_allowlist_is_exactly_http_and_https() -> None:
    """A loopback host is necessary but not sufficient — the scheme is pinned too."""
    assert net_guard._LOCAL_HTTP_SCHEMES == EXPECTED_LOCAL_HTTP_SCHEMES, (
        "net_guard._LOCAL_HTTP_SCHEMES changed. Adding a scheme here lets a model "
        "endpoint reach a non-HTTP URL handler on the local machine (file://, ftp://, "
        "gopher://) — the gap tests/guards/test_endpoint_scheme.py exists to close. "
        "The `# nosec B310` suppression on the urllib opener is justified by this set "
        "being exactly {'http', 'https'}."
    )


def test_the_allowlist_stays_small_enough_to_audit_by_eye() -> None:
    """A guarantee nobody can read at a glance is a guarantee nobody checks."""
    assert len(net_guard._LOOPBACK_HOSTNAMES) == 2


# --------------------------------------------------------------------------------------
# 2. The named regression — the exact edit the audit found to be invisible.
# --------------------------------------------------------------------------------------


def test_the_approved_gateway_hostname_is_not_loopback() -> None:
    """The operator's real gateway, named, so widening for it goes red by name."""
    assert net_guard.is_loopback_host(APPROVED_GATEWAY_HOST) is False
    assert APPROVED_GATEWAY_HOST not in net_guard._LOOPBACK_HOSTNAMES


@pytest.mark.parametrize("scheme", ["http", "https"])
def test_the_approved_gateway_endpoint_is_not_a_local_http_endpoint(scheme: str) -> None:
    """Reaching the gateway must fail the endpoint validator, not just the host check."""
    assert net_guard.is_local_http_endpoint(f"{scheme}://{APPROVED_GATEWAY_HOST}/v1") is False


# --------------------------------------------------------------------------------------
# 3. Behavioural closure — what is ACCEPTED, not merely what is stored.
#    These fire even when the allowlist literal is left untouched and bypassed.
# --------------------------------------------------------------------------------------


@pytest.mark.parametrize("host", _NON_LOOPBACK)
def test_no_non_loopback_host_is_accepted(host: str) -> None:
    assert net_guard.is_loopback_host(host) is False


@pytest.mark.parametrize("host", _LOOPBACK)
def test_every_loopback_host_is_still_accepted(host: str) -> None:
    """The pin must not be satisfiable by breaking the feature (Law 2: never weaken)."""
    assert net_guard.is_loopback_host(host) is True


def test_accepted_hosts_are_exactly_the_expected_ones() -> None:
    """Closure over the whole population in one assertion.

    A widening makes a ``_NON_LOOPBACK`` member appear; a narrowing makes a
    ``_LOOPBACK`` member vanish. Both directions are reported with the offending
    hosts named, which a per-case parametrization cannot do as legibly.
    """
    population = _NON_LOOPBACK + _LOOPBACK
    accepted = {host for host in population if net_guard.is_loopback_host(host)}
    assert accepted == set(_LOOPBACK), (
        f"unexpectedly accepted as local: {sorted(accepted - set(_LOOPBACK))!r}; "
        f"unexpectedly refused: {sorted(set(_LOOPBACK) - accepted)!r}"
    )


def test_no_accepted_name_falls_outside_the_allowlist() -> None:
    """Any accepted *name* (as opposed to IP literal) must BE an allowlist entry.

    This is the property the DoD asks for, stated as closure rather than as samples:
    it holds for hosts nobody thought to enumerate, because acceptance of a non-IP
    name is only ever legitimate via the frozenset.
    """
    for host in _NON_LOOPBACK + _LOOPBACK:
        if not net_guard.is_loopback_host(host):
            continue
        normalized = host.strip().strip("[]").lower()
        try:
            ip_literal = bool(ip_address(normalized).is_loopback)
        except ValueError:
            ip_literal = False
        assert ip_literal or normalized in EXPECTED_LOOPBACK_HOSTNAMES, (
            f"{host!r} was accepted as local but is neither a loopback IP literal nor "
            f"one of {sorted(EXPECTED_LOOPBACK_HOSTNAMES)}"
        )


def test_accepted_schemes_on_a_loopback_host_are_exactly_http_and_https() -> None:
    """Closure over schemes: the host check must not be the only thing standing."""
    accepted = {
        scheme
        for scheme in _SWEPT_SCHEMES
        if net_guard.is_local_http_endpoint(f"{scheme}://127.0.0.1:11434/v1")
    }
    assert accepted == EXPECTED_LOCAL_HTTP_SCHEMES, (
        f"unexpectedly accepted schemes: {sorted(accepted - EXPECTED_LOCAL_HTTP_SCHEMES)!r}; "
        f"unexpectedly refused: {sorted(EXPECTED_LOCAL_HTTP_SCHEMES - accepted)!r}"
    )


@pytest.mark.parametrize("host", [h for h in _NON_LOOPBACK if h.strip() and "/" not in h])
def test_no_non_loopback_host_is_accepted_as_an_endpoint(host: str) -> None:
    """The endpoint validator must refuse the same hosts the host check refuses.

    Guards the composition, not just the parts: ``is_local_http_endpoint`` could be
    rewritten to check the scheme and forget the host.
    """
    literal = f"[{host}]" if host.count(":") > 1 else host
    endpoint = f"https://{literal}/v1/chat/completions"
    # Only assert on endpoints urlparse actually reads back as this host, so a parse
    # quirk can never be mistaken for the guard doing its job.
    if (urlparse(endpoint).hostname or "") != host.lower().strip("[]"):
        pytest.skip(f"{endpoint!r} does not round-trip through urlparse as a host")
    assert net_guard.is_local_http_endpoint(endpoint) is False
