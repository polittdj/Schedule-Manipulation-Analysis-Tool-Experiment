def test_manifest_is_current(entries: list[Any]) -> None:
    """Regenerating must be a no-op. Any intake change lands here first."""
    assert MANIFEST.exists(), "docs/INTAKE-MANIFEST.md is missing — run tools/intake_manifest.py"
    assert MANIFEST.read_text(encoding="utf-8") == tool.render_manifest_markdown(entries), (
        "docs/INTAKE-MANIFEST.md is STALE vs 00_REFERENCE_INTAKE/ — "
        "regenerate with: python tools/intake_manifest.py"
    )


def _manifest_mismatch_paths() -> set[str]:
    """Paths listed in the manifest's mismatch detail table."""
    text = MANIFEST.read_text(encoding="utf-8")
    section = text.split("## Extension&harr;content mismatches", 1)[1].split("## Duplicate", 1)[0]
    return set(re.findall(r"^\| `([^`]+)` \| [\d,]+ \| `", section, flags=re.MULTILINE))


def test_mismatch_ledger_equals_the_measured_set(entries: list[Any]) -> None:
    """The recorded ledger is the derived one — not a hand-kept list that drifted."""
    derived = {e.path for e in entries if e.mismatch}
    assert _manifest_mismatch_paths() == derived
    text = MANIFEST.read_text(encoding="utf-8")
    summary = re.search(r"extension&harr;content mismatches \| (\d+) \|", text)
    assert summary is not None and int(summary.group(1)) == len(derived)


def test_every_tracked_intake_file_is_inventoried(entries: list[Any]) -> None:
    """No file may be scanned-but-unlisted: the full inventory is the whole tracked set."""
    text = MANIFEST.read_text(encoding="utf-8")
    listed = set(re.findall(r"^\| `(00_REFERENCE_INTAKE/[^`]+)` \| ", text, flags=re.MULTILINE))
    assert listed == {e.path for e in entries}


