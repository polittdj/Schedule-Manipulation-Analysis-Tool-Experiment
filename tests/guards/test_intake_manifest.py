def test_every_intake_mpp_is_an_ms_project_ole2_document(entries: list[Any]) -> None:
    """29 native schedules; a rotated .mpp would break the MPXJ conversion path silently.

    The 21st is ``mpp/24Hour Calendar.mpp`` — the ADR-0357 boundary oracle (main d0b703e);
    the 22nd is the root-level ``SRA Large Test File2.mpp`` — the 2026-08-06 SRA parity
    schedule, committed with SSI's SRA + Sensitivity workbooks (main f1f13f9); the 23rd-28th
    are the six FX tamper fixtures (``mpp/*_FX0[1-6]_*.mpp``), the operator's 2026-08-07
    MS Project conversions of the single-variable MSPDI fixtures (main 9ba7203) — all six
    verified genuine OLE2 and readable by the vendored MPXJ. NOTE (read-only audit
    2026-08-07): the FX-03/FX-04 conversions do NOT carry their duration cuts — MS Project
    re-derived Duration from the stale stored dates on import — so those two are
    byte-genuine .mpp files whose Fuse exports oracle the UNCHANGED schedules. The 29th is
    ``ssi/SRA Large Test File2.mpp`` — the operator's 2026-08-12 upload of the SAME schedule
    alongside a SECOND SSI run and this tool's own SRA/Sensitivity exports, so the pair can be
    compared directly (see ``docs/PLAN/SRA-VS-SSI-LARGE-TEST-FILE2.md``). It is a second copy of
    the root-level file, not a new schedule."""
    mpp = [e for e in entries if e.ext == ".mpp"]
    assert len(mpp) == 29
    assert {e.family for e in mpp} == {"ole2-project"}


def test_the_project5_family_is_the_shape_adr_0112_relies_on(entries: list[Any]) -> None:
    """R-03's "two source .mpp" are tracked twice each — and one pair is NOT byte-identical.

    Measured 2026-08-03: the two ``Project5_TAMPERED.mpp`` copies differ in 102 of 817,152 bytes,
    entirely inside the OLE2 VBA-project storage. Both import to an equal ``Schedule`` (145 tasks,
    identical calendars, identical CPM timings, the same 4-task critical path) — no parity
    exposure. Pinned here so the divergence stays a documented fact rather than a discovery.
    """
    by_path = {e.path: e for e in entries}
    root2 = by_path["00_REFERENCE_INTAKE/Project2.mpp"]
    sub2 = by_path["00_REFERENCE_INTAKE/mpp/Project2.mpp"]
    assert root2.sha256 == sub2.sha256, "Project2.mpp copies diverged"

    root5 = by_path["00_REFERENCE_INTAKE/Project5_TAMPERED.mpp"]
    sub5 = by_path["00_REFERENCE_INTAKE/mpp/Project5_TAMPERED.mpp"]
    alias5 = by_path["00_REFERENCE_INTAKE/mpp/Project5.mpp"]
    assert root5.size == sub5.size == 817152
    assert root5.sha256 != sub5.sha256, "the known VBA-storage divergence has been resolved"
    assert sub5.sha256 == alias5.sha256, "mpp/Project5.mpp is the documented tampered-file alias"


def test_shipped_static_assets_are_not_mislabelled() -> None:
    """The rotation never reached the product. 67 vendored assets, each matching its extension.

    65 -> 67 in ADR-0426 (``launch.js`` + ``launch.css``, the boot screen). The count is pinned
    deliberately: this guard's subject is a bulk-upload rotation that mislabelled 99 intake files,
    so a NEW shipped asset must be an explicit decision rather than something that slips in under
    a glob.
    """
    assets = sorted(p for p in STATIC.iterdir() if p.is_file())
    assert len(assets) == 67
    wrong = {
        p.name: tool.detect_family(p.read_bytes())
        for p in assets
        if tool.is_mismatch(p.suffix.lower(), tool.detect_family(p.read_bytes()))
    }
    assert wrong == {}


