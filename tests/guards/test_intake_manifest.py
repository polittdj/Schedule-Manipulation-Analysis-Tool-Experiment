"""Pin the provenance of ``00_REFERENCE_INTAKE/`` (audit P1, ADR-0347).

The 2026-08-03 external audit found the committed reference intake (ADR-0151/0152, non-CUI) had
arrived from its bulk upload with a **name/content rotation**: files whose extension their bytes
contradict. Nothing the product reads was affected — but with no manifest there was no way to tell
an *inherited* mislabel from a *new* one, and no way to prove the parity inputs were untouched.

``docs/INTAKE-MANIFEST.md`` is that measurement, generated by ``tools/intake_manifest.py``. These
tests do two different jobs and both matter:

* **Sync** — re-derive the whole scan and compare. Any added, removed, renamed or byte-changed
  intake file fails here, as does any new extension/content mismatch. This is the regression guard.
* **Live** — assert the assets the engine actually depends on are intact, *without* consulting the
  manifest. A manifest that merely agreed with itself would prove nothing; these read the bytes.

The manifest hashes the committed **blob**, not the working tree, because ``.gitattributes`` sets
``* text=auto`` — 128 of these files check out CRLF on Windows and LF on Linux.
"""

from __future__ import annotations

import importlib.util
import re
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path
from types import ModuleType
from typing import Any

import pytest

ROOT = Path(__file__).resolve().parents[2]
INTAKE = ROOT / "00_REFERENCE_INTAKE"
MANIFEST = ROOT / "docs" / "INTAKE-MANIFEST.md"
STATIC = ROOT / "src" / "schedule_forensics" / "web" / "static"


def _load_tool() -> ModuleType:
    """Import ``tools/intake_manifest.py``; ``tools/`` is not a package (see test_battery.py)."""
    path = ROOT / "tools" / "intake_manifest.py"
    spec = importlib.util.spec_from_file_location("intake_manifest", path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    # Registered before exec: @dataclass resolves annotations through sys.modules.
    sys.modules["intake_manifest"] = module
    spec.loader.exec_module(module)
    return module


tool = _load_tool()


@pytest.fixture(scope="module")
def entries() -> list[Any]:
    """One scan shared by the whole module — it streams ~317 MB of blobs."""
    if not INTAKE.is_dir():  # defensive, mirroring the .aft/.mpp skips
        pytest.skip("00_REFERENCE_INTAKE/ not present in this checkout")
    scanned = tool.scan(ROOT)
    if not scanned:
        pytest.skip("00_REFERENCE_INTAKE/ tracks no files in this checkout")
    return list(scanned)


