def test_detection_is_decisive_not_speculative() -> None:
    """A fabricated mismatch would be worse than the drift it chases (Law 2)."""
    # No signature and not UTF-8 -> "binary", which is never a mismatch under any extension.
    assert tool.detect_family(b"\xff\xfe\x00\x01nonsense") == "binary"
    assert tool.is_mismatch(".png", "binary") is False

    # An extension with no standardised signature carries no expectation at all.
    assert tool.is_mismatch(".afw2", "png") is False

    # A JS object literal opens with "{" but is not JSON -> plain text, not a false ".js is JSON".
    assert tool.detect_family(b"{ready: 1, /* trailing */}") == "text"
    assert tool.is_mismatch(".js", "text") is False

    # Whole-file parse only: a prefix that looks like JSON does not make the file JSON.
    assert tool.detect_family(b'{"a": 1}\nnot json anymore\n') == "text"
    assert tool.detect_family(b'{"a": 1}') == "json"

    # ...and a real contradiction IS reported.
    assert tool.is_mismatch(".png", "jpeg") is True
    assert tool.is_mismatch(".json", "text") is True


def test_manifest_generator_check_mode_agrees_with_the_committed_file() -> None:
    """``--check`` is what a human runs; it must not disagree with the in-process comparison."""
    proc = subprocess.run(
        [sys.executable, "tools/intake_manifest.py", "--check"],
        cwd=ROOT,
        capture_output=True,
        text=True,
    )
    assert proc.returncode == 0, proc.stderr
